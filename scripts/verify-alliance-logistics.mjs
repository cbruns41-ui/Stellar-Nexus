import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
export async function verifyAllianceLogistics({db,snap,send,evaluate,until,click,shot}) {
 const game=require('../src/game'),social=require('../src/social');
 const leader=db.prepare('SELECT * FROM empires WHERE id=?').get(snap.empire.id),home=game.homePlanetOf(db,leader.id);
 const alliance=social.createAlliance(db,leader,'LOG','Logistics Test','','#44aaff');
 const target=db.prepare('SELECT * FROM planets WHERE empire_id IS NULL AND system_id=? LIMIT 1').get(home.system_id);
 db.prepare("UPDATE planets SET empire_id=?,alliance_id=?,name='Logistics HQ',metal=0,helium=0,titan=0,energy=0,crystal=0,diamond=0 WHERE id=?").run(leader.id,alliance.id,target.id);
 const cost=social.ALLIANCE_RESEARCH.supply_grid.cost;
 for(const [id,n] of Object.entries(cost))db.prepare(`UPDATE planets SET ${id}=? WHERE id=?`).run(n-(id==='metal'?100:0),target.id);
 db.prepare('UPDATE planets SET metal=10000,helium=10000,last_tick=? WHERE id=?').run(Date.now(),home.id);
 game.addShips(db,home.id,{cargo:2});
 await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
 await send('Page.reload');await until(`document.querySelector('#planet-select option[value="${target.id}"]')`);
 await evaluate(`document.querySelector('[data-view="alliance"]').click()`);
 await until(`document.querySelector('[data-alliance-transport="${target.id}"]:not([data-collect])')`);
 const openTransport=async collect=>{
   const selector=`[data-alliance-transport="${target.id}"]${collect?'[data-collect]':':not([data-collect])'}`;
   await evaluate(`document.querySelector('${selector}').scrollIntoView({block:'center'})`);await click(selector);
   await until(`document.querySelector('#mission')?.value==='${collect?'collect':'transport'}'`);
   await evaluate(`{const input=document.querySelector('#ship-picks [data-ship="cargo"]');input.value='1';input.dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('[data-cargo="metal"]').value='100';}`);
   await until(`document.querySelector('#travel-box').textContent.includes('Flugzeit') && !document.querySelector('#m-go').disabled`);
   await evaluate(`document.querySelector('#m-go').scrollIntoView({block:'center'})`);await click('#m-go');await until(`!document.querySelector('#m-go')`);
 };
 await openTransport(false);
 const transport=db.prepare("SELECT * FROM fleets WHERE empire_id=? AND mission='transport' AND is_return=0 ORDER BY id DESC LIMIT 1").get(leader.id);
 assert.equal(transport.origin_planet_id,home.id);assert.equal(transport.target_planet_id,target.id);
 assert.equal(JSON.parse(transport.cargo).metal,100);
 db.prepare('UPDATE fleets SET arrives_at=1 WHERE id=?').run(transport.id);
 await evaluate(`{const s=document.querySelector('#planet-select');s.value='${target.id}';s.dispatchEvent(new Event('change',{bubbles:true}));}`);
 await until(`document.querySelector('#planet-select').value==='${target.id}' && !document.querySelector('#game').classList.contains('focus-pending')`);
 assert.equal(db.prepare('SELECT metal FROM planets WHERE id=?').get(target.id).metal,cost.metal);
 await evaluate(`document.querySelector('[data-view="research"]').click()`);
 await until(`document.querySelector('[data-ally-tech="supply_grid"]:not([disabled])')`);
 await evaluate(`document.querySelector('[data-ally-tech="supply_grid"]').scrollIntoView({block:'center'})`);
 await click('[data-ally-tech="supply_grid"]');
 await until(`document.querySelector('#panel-view').textContent.includes('Forschung läuft')`);
 assert.equal(db.prepare('SELECT metal FROM planets WHERE id=?').get(target.id).metal,0);
 assert.equal(social.researchRows(db,alliance.id,leader.id).find(r=>r.id==='supply_grid').progress,1);
 await shot('alliance-logistics-research-running');
 db.prepare("UPDATE queue SET completes_at=1 WHERE planet_id=? AND kind='ally_research'").run(target.id);
 await evaluate(`fetch('/api/state').then(r=>r.json())`);
 assert.equal(social.allianceBonuses(db,leader.id).prod,.01);
 db.prepare('UPDATE planets SET metal=250 WHERE id=?').run(target.id);
 await evaluate(`document.querySelector('[data-view="alliance"]').click()`);
 await until(`document.querySelector('[data-collect]')`);
 await openTransport(true);
 const collect=db.prepare("SELECT * FROM fleets WHERE empire_id=? AND mission='collect' AND is_return=0 ORDER BY id DESC LIMIT 1").get(leader.id);
 assert.equal(JSON.parse(collect.cargo).requestedCargo.metal,100);
 db.prepare('UPDATE fleets SET arrives_at=1 WHERE id=?').run(collect.id);
 await evaluate(`fetch('/api/state').then(r=>r.json())`);
 assert.equal(db.prepare('SELECT metal FROM planets WHERE id=?').get(target.id).metal,150);
 assert.equal(JSON.parse(db.prepare('SELECT cargo FROM fleets WHERE id=?').get(collect.id).cargo).metal,100);
 console.log('Alliance logistics browser passed: mobile transport, warehouse credit, research start/completion and requested collection');
}
